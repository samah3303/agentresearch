"""
State schema for the AgentResearch LangGraph workflow.
Uses TypedDict for type-safe state management across agents.
"""

from __future__ import annotations

from typing import Annotated, Any, Optional, TypedDict

from langgraph.graph.message import add_messages


class ResearchSource(TypedDict, total=False):
    """A single research source found by the Researcher agent."""

    title: str
    url: str
    snippet: str
    relevance_score: float


class AgentState(TypedDict, total=False):
    """Complete state for the multi-agent research workflow."""

    # ── Input ──
    topic: str
    """The research topic provided by the user."""

    # ── Messages (for LLM conversation history) ──
    messages: Annotated[list[Any], add_messages]
    """LangGraph-managed message history (auto-append)."""

    # ── Researcher outputs ──
    search_queries: list[str]
    """Queries generated by the Researcher for web search."""

    research_sources: list[ResearchSource]
    """Raw search results gathered from DuckDuckGo."""

    research_findings: str
    """Summarized research findings from the Researcher agent."""

    # ── Analyst outputs ──
    analysis: str
    """Analysis report: patterns, insights, gaps identified by Analyst."""

    key_insights: list[str]
    """Bullet-point key insights extracted from the research."""

    identified_gaps: list[str]
    """Knowledge gaps the Analyst identified for further research."""

    # ── Fact-Checker outputs (optional) ──
    fact_check_results: str
    """Verification report for claims made by other agents."""

    fact_check_score: float
    """Overall factuality score (0.0 - 1.0)."""

    # ── Writer outputs ──
    final_report: str
    """The final polished Markdown research report."""

    report_json: dict[str, Any]
    """Structured JSON version of the report."""

    # ── Human-in-the-loop ──
    human_feedback: str
    """Feedback provided by the user at the review step."""

    human_approved: bool
    """Whether the user approved the intermediate analysis."""

    # ── Workflow control ──
    status: str
    """Current workflow status: 'idle', 'researching', 'analyzing',
    'awaiting_review', 'writing', 'fact_checking', 'completed', 'error'."""

    error_message: str
    """Error message if status is 'error'."""

    # ── Metadata ──
    session_id: str
    """Unique session identifier."""

    timestamp: str
    """ISO-formatted timestamp of session creation."""


def create_initial_state(topic: str, session_id: str = "") -> AgentState:
    """Create a fresh state with the given topic."""
    from datetime import datetime, timezone
    import uuid

    return AgentState(
        topic=topic,
        messages=[],
        search_queries=[],
        research_sources=[],
        research_findings="",
        analysis="",
        key_insights=[],
        identified_gaps=[],
        fact_check_results="",
        fact_check_score=0.0,
        final_report="",
        report_json={},
        human_feedback="",
        human_approved=False,
        status="idle",
        error_message="",
        session_id=session_id or str(uuid.uuid4()),
        timestamp=datetime.now(timezone.utc).isoformat(),
    )
